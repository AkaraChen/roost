//! `Object`, the root of every class hierarchy.

use std::any::Any;

use crate::Ref;
use crate::cast::CastRequest;
use crate::gc::Trace;

/// `java.lang.Object` as a type: `Ref<Object>` holds any object, like `Ref<Animal>` holds
/// any `Animal`. (`Object` is to [`ObjectClass`] what `Animal` is to `AnimalClass`.)
pub type Object = dyn ObjectClass;

/// `&self` as `&dyn Any`, dispatched through the vtable.
///
/// Blanket-implemented for every (sized) [`ObjectClass`], and a supertrait of `ObjectClass`, so it is
/// in every class trait's vtable: `animal.as_any()` on a `&dyn Animal` yields the concrete
/// class. Only implemented for `ObjectClass`es on purpose: a blanket impl for all `T: Any` would
/// also match `Ref<dyn Animal>` itself, and method lookup on a `Ref` would then stop at the
/// reference instead of reaching the object.
pub trait AsAny: Any {
    fn as_any(&self) -> &dyn Any;
}

impl<T: ObjectClass> AsAny for T {
    fn as_any(&self) -> &dyn Any {
        self
    }
}

/// The root class trait, `java.lang.Object`. Every class trait (`trait AnimalClass:
/// ObjectClass`) and interface trait has it as a supertrait, so these methods are in every
/// vtable.
///
/// Implementations are meant to be generated by `class!`; the only required method,
/// [`__roost_casts`](ObjectClass::__roost_casts), says what the object can be cast to.
/// `to_string`, `equals` and `hash_code` can be overridden in `class!` with `@Override`.
pub trait ObjectClass: Trace + AsAny {
    /// Offers `self` as each type it can be viewed as: its own class, and the trait of each
    /// class it (transitively) extends and each interface it implements.
    /// [`Ref::cast`](crate::Ref::cast) and [`Ref::instance_of`](crate::Ref::instance_of)
    /// are answered from this list.
    ///
    /// ```ignore
    /// fn __roost_casts(&self, req: &mut CastRequest<'_>) {
    ///     req.offer_class(self)          // Ref<Puppy>
    ///         .offer::<dyn Dog, _>(self) // Ref<dyn Dog>
    ///         .offer::<dyn Animal, _>(self)
    ///         .offer::<Object, _>(self);
    /// }
    /// ```
    #[doc(hidden)]
    fn __roost_casts(&self, req: &mut CastRequest<'_>);

    /// Name of the runtime class. Defaults to the Rust type name; `class!` overrides it.
    fn class_name(&self) -> &'static str {
        std::any::type_name::<Self>()
    }

    /// Java's `hashCode()`. The default is the identity hash: derived from the object's
    /// address, which never changes because the collector does not move objects. Equal for
    /// two references iff [`Ref::ptr_eq`] (modulo collisions of the fold to 32 bits).
    fn hash_code(&self) -> i32 {
        identity_hash_code(self)
    }

    /// Java's `equals(Object)`. The default is identity: `true` iff `other` is this very
    /// object.
    ///
    /// The other object comes as a `Ref<Object>`, so an override can [`cast`](Ref::cast)
    /// it (`other.cast::<Point>()`); any reference coerces to it: `a.equals(b.clone())`.
    fn equals(&self, other: Ref<Object>) -> bool {
        identity_equals(self, &other)
    }

    /// Java's `toString()`. The default is `ClassName@hexHash`. `Display` on a `Ref` (and
    /// so `format!("{r}")`, `r.to_string()`) goes through it.
    fn to_string(&self) -> String {
        default_to_string(self)
    }
}

// The defaults as functions: `super.to_string()` reaches them when no class in between
// overrides the method (the trait's own default can't be called once it is overridden).

/// `Object.hashCode()`: from the object's address.
pub fn identity_hash_code<T: ?Sized>(this: &T) -> i32 {
    let addr = (this as *const T).cast::<u8>() as usize as u64;
    // Objects are at least 8-byte aligned inside a GcBox: drop the always-zero bits.
    let addr = addr >> 3;
    (addr ^ (addr >> 32)) as u32 as i32
}

/// `Object.equals(other)`: identity.
pub fn identity_equals<T: ?Sized>(this: &T, other: &Ref<Object>) -> bool {
    std::ptr::addr_eq(this as *const T, &**other as *const Object)
}

/// `Object.toString()`: `ClassName@hexHash`, through the (virtual) `class_name` and
/// `hash_code`.
pub fn default_to_string<T: ?Sized + ObjectClass>(this: &T) -> String {
    format!("{}@{:x}", this.class_name(), this.hash_code())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::test_classes::*;

    #[test]
    fn default_class_name_is_the_runtime_type() {
        let a: Ref<dyn Animal> = puppy("Rex");
        assert_eq!(a.class_name(), "roost::test_classes::Puppy");
        let c: Ref<dyn Animal> = cat("Tom");
        assert_eq!(c.class_name(), "Cat");
    }

    #[test]
    fn default_to_string_is_class_at_hex_hash() {
        let a: Ref<dyn Animal> = plain("Blob");
        let expected = format!("roost::test_classes::PlainAnimal@{:x}", a.hash_code());
        assert_eq!(ObjectClass::to_string(&*a), expected);
        assert_eq!(a.to_string(), expected); // Display on Ref goes through the same method
    }

    #[test]
    fn hash_code_is_per_object_and_stable() {
        let p = puppy("Rex");
        let as_animal: Ref<dyn Animal> = p.clone();
        let as_object: Ref<Object> = p.clone();
        // Same object, any static type: same hash.
        assert_eq!(p.hash_code(), as_animal.hash_code());
        assert_eq!(p.hash_code(), as_object.hash_code());
        // Survives a collection (the collector doesn't move objects).
        let before = p.hash_code();
        crate::gc::collect();
        assert_eq!(p.hash_code(), before);
        // Distinct live objects get distinct hashes (in practice; not guaranteed in general).
        let others: Vec<Ref<Puppy>> = (0..100).map(|_| puppy("x")).collect();
        let mut hashes: Vec<i32> = others.iter().map(|o| o.hash_code()).collect();
        hashes.push(before);
        hashes.sort_unstable();
        hashes.dedup();
        assert_eq!(hashes.len(), 101);
    }

    #[test]
    fn equals_is_identity() {
        let a = plain("Blob");
        let a2: Ref<Object> = a.clone();
        let b = plain("Blob");
        assert!(a.equals(a2));
        assert!(!a.equals(b));
    }

    #[test]
    fn as_any_reaches_the_concrete_object_through_a_trait_object() {
        let a: Ref<dyn Animal> = puppy("Rex");
        // Method lookup on the `Ref` lands on the object, not on the `Ref` itself.
        let any = a.as_any();
        assert!(any.is::<Puppy>());
        assert_eq!(any.downcast_ref::<Puppy>().unwrap().name, "Rex");
        assert!(any.downcast_ref::<Mutt>().is_none());
    }
}
